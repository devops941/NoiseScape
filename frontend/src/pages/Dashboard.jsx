import React, { useState, useEffect } from 'react';
import { Volume2, Radio, AlertTriangle, ShieldCheck, Activity, BrainCircuit } from 'lucide-react';
import { useNoise } from '../context/NoiseContext';
import { readingService } from '../services/readingService';
import StatCard from '../components/common/StatCard';
import NoiseMap from '../components/map/NoiseMap';
import NoiseTrendChart from '../components/charts/NoiseTrendChart';
import AlertList from '../components/alerts/AlertList';
import AreaNoiseChecker from '../components/common/AreaNoiseChecker';
import RandomAreaPredictor from '../components/common/RandomAreaPredictor';
import LiveMicMeter from '../components/common/LiveMicMeter';

export default function Dashboard() {
  const { stations, summary, alerts } = useNoise();
  const [recentReadings, setRecentReadings] = useState([]);

  useEffect(() => {
    readingService.getReadings({ limit: 25 })
      .then(setRecentReadings)
      .catch(() => setRecentReadings([]));
  }, [summary]);

  return (
    <div className="space-y-6">
      {/* 1. Core Feature: Machine Learning Noise Predictor for ANY Random Area */}
      <RandomAreaPredictor />

      {/* 2. Area Noise & Safety Checker (Existing Monitored Hubs) */}
      <AreaNoiseChecker stations={stations} />

      {/* 3. Pure Software Sound Meter (Using Laptop/Mobile Microphone - Zero IoT) */}
      <LiveMicMeter />

      {/* 4. Metric Stat Cards Grid */}
      <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-4 gap-4">
        <StatCard
          title="Avg Ambient Noise"
          value={summary?.average_ambient_db ?? '64.5'}
          unit="dB(A)"
          icon={Volume2}
          color="blue"
          trend="Citywide acoustic mean"
        />
        <StatCard
          title="Monitored Sectors"
          value={summary?.active_stations ?? stations.length}
          unit={`/ ${summary?.total_stations ?? stations.length}`}
          icon={Radio}
          color="emerald"
          trend="Madurai urban sectors"
        />
        <StatCard
          title="Detected Breaches"
          value={summary?.active_alerts_count ?? alerts.length}
          unit="Events"
          icon={AlertTriangle}
          color="red"
          trend="CPCB regulatory violations"
        />
        <StatCard
          title="Analyzed Records"
          value={summary?.total_readings_logged ?? '1,008'}
          unit="Samples"
          icon={ShieldCheck}
          color="amber"
          trend="Dataset training records"
        />
      </div>

      {/* 5. Geospatial Map + Trend Chart */}
      <div className="grid grid-cols-1 lg:grid-cols-3 gap-4">
        <div className="lg:col-span-2 space-y-2">
          <div className="flex items-center justify-between">
            <h3 className="text-xs font-bold uppercase tracking-wider text-slate-300 flex items-center gap-2">
              <span className="w-2 h-2 rounded-full bg-sky-400 animate-ping" />
              Live Geospatial Sound Dispersion Heatmap
            </h3>
            <span className="text-[11px] text-slate-400 font-mono">Madurai District Grid</span>
          </div>
          <div className="h-[370px]">
            <NoiseMap stations={stations} />
          </div>
        </div>

        <div className="space-y-2">
          <div className="flex items-center justify-between">
            <h3 className="text-xs font-bold uppercase tracking-wider text-slate-300">
              Acoustic Profile Stream
            </h3>
            <span className="text-[11px] text-sky-400 font-mono">Historical Acoustic Data</span>
          </div>
          <NoiseTrendChart readings={recentReadings} />
        </div>
      </div>

      {/* 6. Alert Incident Feed */}
      <div className="space-y-3">
        <div className="flex items-center justify-between">
          <h3 className="text-xs font-bold uppercase tracking-wider text-slate-300">
            Real-time Threshold Breach Feed
          </h3>
          <span className="text-[11px] text-slate-400 font-medium">Auto-generated by CPCB Rules Engine</span>
        </div>
        <AlertList alerts={alerts.slice(0, 5)} />
      </div>
    </div>
  );
}
